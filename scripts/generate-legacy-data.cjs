fs.mkdirSync(outputDir, { recursive: true });
for (const [name, source] of registry) {
  const input = fs.readFileSync(path.join(root, `src/${source}.ts`), 'utf8');
  const output = ts.transpileModule(input, {
    compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext },
  }).outputText.replace(/^import .*;\s*$/gm, '').replace(/^export \{[^\n]*\} from [^\n]*;\s*$/gm, '').replace(/^export /gm, '');
  fs.writeFileSync(path.join(outputDir, `${name}.js`),
    `// GENERATED from src/${source}.ts — do not edit.\n${output}`);
}
// Manifest lets the VM regression loader stay independent of the browser entry.
